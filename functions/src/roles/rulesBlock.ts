/**
 * Module 4d step 3 — the part of firestore.rules that knows the role matrix. GENERATED from permRules.ts so the
 * rules can never drift from the server: `node tools/gen-role-rules.mjs` rewrites the block between the markers in
 * firestore.rules, and test/module4f.test.ts fails when the file and this generator disagree.
 */
import { MODULES, ROLES, SENSITIVE, allowed } from "./permRules";

export const RULES_BLOCK_START = "    // >>> job-role matrix (generated by tools/gen-role-rules.mjs from functions/src/roles/permRules.ts — do not edit by hand)";
export const RULES_BLOCK_END = "    // <<< job-role matrix";

/** One compact line per role — "level;C:,mod,mod,;E:,mod,;S:,sensitive kind,;" — so the rules evaluate a small map, not a big one. */
export function roleRow(code: (typeof ROLES)[number]["code"], level: string): string {
  const part = (a: "C" | "E") => `${a}:,${MODULES.filter((m) => allowed(code, m, a)).map((m) => m + ",").join("")}`;
  const sees = Object.entries(SENSITIVE).filter(([, roles]) => (roles as readonly string[]).includes(code)).map(([k]) => k + ",").join("");
  return `${level};${part("C")};${part("E")};S:,${sees};`;
}

export function rulesRoleBlock(): string {
  const rows = ROLES.filter((r) => r.code !== "owner").map((r) => `        '${r.code}': '${roleRow(r.code, r.level)}'`).join(",\n");
  return [
    RULES_BLOCK_START,
    "    // role -> 'level;C:,modules it may Create in,;E:,modules it may Edit in,;S:,sensitive figures it may see,;'",
    "    function jobMatrix() {",
    "      return {",
    rows,
    "      };",
    "    }",
    "",
    "    // May the signed-in person's business role do this action ('C' or 'E') in one of these modules",
    "    // ('customers|events')? It only NARROWS: true for the owner, for a login with no role (or a role of",
    "    // another level), and for worker / driver staff (their everyday work is not narrowed). The read-only",
    "    // Auditor gets false for every write.",
    "    function jobMay(mods, action) {",
    "      let u = me();",
    "      let level = u.get('role', '');",
    "      let row = jobMatrix().get(u.get('jobRole', ''), '');",
    "      return row == ''",
    "             || !row.matches(level + ';.*')",
    "             || (level == 'staff' && u.get('jobRole', '') != 'auditor')",
    "             || row.matches('.*;' + action + ':[^;]*,(' + mods + '),.*');",
    "    }",
    "",
    "    // B4: may the signed-in person's business role see this sensitive figure ('salary', 'foodCost' …)?",
    "    // Narrows only, like jobMay.",
    "    function jobSees(kind) {",
    "      let u = me();",
    "      let level = u.get('role', '');",
    "      let row = jobMatrix().get(u.get('jobRole', ''), '');",
    "      return row == ''",
    "             || !row.matches(level + ';.*')",
    "             || (level == 'staff' && u.get('jobRole', '') != 'auditor')",
    "             || row.matches('.*;S:[^;]*,' + kind + ',.*');",
    "    }",
    RULES_BLOCK_END,
  ].join("\n");
}
