#!/usr/bin/env python3
"""Usage: python3 tools/hi/phone/apply.py <name> <start> — reads a Python list of Hindi texts from stdin and pairs it with
todo-static.json[start:start+len] (patterns: use --p with todo-patterns.json). Writes batch-<name>.json / pbatch-<name>.json.
Pairing by position avoids retyping the English; todo-*.json must be freshly generated by phone_extract.py (and not
changed between making the chunk and applying it)."""
import sys, json, os, ast
here = os.path.dirname(os.path.abspath(__file__))
pat = '--p' in sys.argv
args = [a for a in sys.argv[1:] if a != '--p']
name, start = args[0], int(args[1])
hi = ast.literal_eval(sys.stdin.read())
assert hi, 'empty list: refusing to overwrite a batch'
todo = json.load(open(os.path.join(here, 'todo-patterns.json' if pat else 'todo-static.json'), encoding='utf-8'))
chunk = todo[start:start + len(hi)]
assert len(chunk) == len(hi), (len(chunk), len(hi))
json.dump(dict(zip(chunk, hi)), open(os.path.join(here, ('pbatch-' if pat else 'batch-') + name + '.json'), 'w', encoding='utf-8'), ensure_ascii=False, indent=0)
print('wrote', len(hi))
