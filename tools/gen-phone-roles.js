// Writes the phone's copy of the role list (JobRoles.kt) from functions/src/roles/permRules.ts.
// Run from the project folder after `cd functions && npm test`:  node tools/gen-phone-roles.js
const { ROLES, modulesOf } = require("../functions/lib-test/src/roles/permRules.js");
const esc = (s) => JSON.stringify(s);
const out = `package com.example.suseelacateringcrm.data.model

import androidx.compose.runtime.getValue
import androidx.compose.runtime.mutableStateOf
import androidx.compose.runtime.setValue
import com.example.suseelacateringcrm.ui.navigation.NavRoutes

/**
 * Module 4d — the 17 business roles on the phone. GENERATED by tools/gen-phone-roles.js from
 * functions/src/roles/permRules.ts (ROLES and modulesOf) — do not edit by hand.
 *
 * It only decides which drawer items a person sees — it hides, it never grants. The security level and the server
 * (callables + Firestore rules) decide what a person can actually do.
 */
data class JobRole(val code: String, val level: String, val te: String, val en: String)

object JobRoles {
    /** The signed-in person's business role ("" = none given). Set by the nav graph from users/{uid}.jobRole. */
    var current by mutableStateOf("")

    val ALL: List<JobRole> = listOf(
${ROLES.map((r) => `        JobRole(${esc(r.code)}, ${esc(r.level)}, ${esc(r.te)}, ${esc(r.en)}),`).join("\n")}
    )

    /** Modules each manager-level role may open (the View column of the permission matrix). */
    private val MODULES: Map<String, Set<String>> = mapOf(
${ROLES.filter((r) => r.level === "manager").map((r) => `        ${esc(r.code)} to setOf(${modulesOf(r.code).map(esc).join(", ")}),`).join("\n")}
    )

    /** Drawer route -> module of the matrix. A route that is not listed is shown to everyone who passes the level check. */
    private val ROUTE_MODULE: Map<String, String> = mapOf(
        NavRoutes.DASHBOARD to "reports", NavRoutes.LEADS_LIST to "leads", NavRoutes.CUSTOMERS_LIST to "customers", NavRoutes.BOOKINGS_LIST to "bookings",
        NavRoutes.QUOTATIONS_LIST to "quotations", NavRoutes.QUOTE_BUILDER to "quotations", NavRoutes.MENU_PACKAGES to "recipes", NavRoutes.MENU_LIST to "recipes",
        NavRoutes.KITCHEN to "production", NavRoutes.INVENTORY_LIST to "inventory", NavRoutes.DAY_PLAN to "production", NavRoutes.DISHES to "recipes",
        NavRoutes.EQUIPMENT to "equipment", NavRoutes.VEHICLES to "vehicles", NavRoutes.OUTSIDE_ORDERS to "purchaseOrders", NavRoutes.PACKED_PRODUCTS to "inventory",
        NavRoutes.PROCUREMENT to "purchaseRequests", NavRoutes.COMPLAINTS to "events", NavRoutes.LUNCH_BOXES to "bookings", NavRoutes.CONTENT_PLAN to "marketing",
        NavRoutes.INVOICES_LIST to "invoices", NavRoutes.EXPENSES_LIST to "expenses", NavRoutes.PURCHASES_LIST to "vendorBills", NavRoutes.VENDOR_RATES to "vendors",
        NavRoutes.ATTENDANCE to "attendance",
    )

    /**
     * Should this drawer item be shown? Only narrows, and only for a manager login that was given a manager-level
     * role: the owner, a login with no role, and staff logins (worker / driver / auditor) see what their level shows.
     */
    fun navAllowed(route: String, role: UserRole?, jobRole: String = current): Boolean {
        if (role != UserRole.MANAGER) return true
        val modules = MODULES[jobRole] ?: return true
        val module = ROUTE_MODULE[route] ?: return true
        return module in modules
    }
}
`;
require("fs").writeFileSync(require("path").join(__dirname, "../app/src/main/java/com/example/suseelacateringcrm/data/model/JobRoles.kt"), out);
console.log("JobRoles.kt written");
